import { Schema, model, models } from "mongoose";
const schema = new Schema(
  {
    sku: { type: String, required: true, unique: true },
    slug: { type: String, required: true, unique: true },
    name: { type: String, required: true },
    parentSku: { type: String, index: true },
    attributes: [{ name: String, value: String }],
    specifications: [{ name: String, value: String }],
    images: [String],
    tags: [String],
    inventoryVersion: { type: Number, default: 0 },
    taxCode: String,
    weightGrams: { type: Number, min: 0 },
    category: { type: String, required: true },
    tagline: String,
    brand: String,
    gtin: String,
    mpn: String,
    condition: {
      type: String,
      enum: ["new", "refurbished", "used"],
      default: "new",
    },
    description: String,
    prices: { type: Schema.Types.Mixed, required: true },
    marketPrices: Schema.Types.Mixed,
    marketPriceTimestamp: Number,
    image: { type: String, required: true },
    features: [String],
    stock: { type: Number, required: true, default: 0, min: 0 },
    active: { type: Boolean, default: false },
    featured: { type: Boolean, default: false },
  },
  { timestamps: true },
);
export const Product = models.Product || model("Product", schema);
